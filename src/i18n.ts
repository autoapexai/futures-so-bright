/**
 * Put the static page text in the current language. The English strings are exactly the text
 * index.html already has, so in English this changes nothing.
 */
export function applyDomStrings(): void {
  const info = LANGS.find((l) => l.id === current) ?? LANGS[0];
  if (document.documentElement.lang !== info.html) document.documentElement.lang = info.html;
  for (const [sel, key, attr, lead] of DOM) {
    const v = t(key);
    document.querySelectorAll<HTMLElement>(sel).forEach((el) => {
      if (attr) {
        if (el.getAttribute(attr) !== v) el.setAttribute(attr, v);
      } else if (lead) {
        const n = el.firstChild;
        if (n && n.nodeType === Node.TEXT_NODE) {
          if (n.nodeValue !== v) n.nodeValue = v;
        } else el.insertBefore(document.createTextNode(v), n);
      } else if (el.textContent !== v) el.textContent = v;
    });
  }
  document.querySelectorAll<HTMLElement>('#lang-row .lang-opt').forEach((b) => {
    const on = b.dataset.lang === current;
    b.classList.toggle('selected', on);
    b.setAttribute('aria-pressed', on ? 'true' : 'false');
  });
  const label = document.getElementById('lang-label');
  if (label && label.textContent !== t('lang_label')) label.textContent = t('lang_label');
}

/**
 * Canvas fonts. Orbitron and Rajdhani have no Vietnamese or Chinese glyphs, so a per-glyph
 * fallback would mix faces inside a word. Vietnamese swaps them for Exo 2 / Chakra Petch (same
 * techno feel, full Vietnamese; loaded on demand); Chinese keeps them for Latin and digits and
 * puts the system Simplified Chinese fonts ahead of the generic family. English is untouched.
 */
const CJK = "'PingFang SC', 'Hiragino Sans GB', 'Microsoft YaHei', 'Noto Sans CJK SC', 'Noto Sans SC', 'Source Han Sans SC', 'WenQuanYi Micro Hei'";
const VI_FALLBACK = "'Be Vietnam Pro', 'Segoe UI', Roboto, 'Noto Sans', Arial";
const fontCache = new Map<string, string>();
export function localFont(font: string): string {
  if (current === 'en' || current === 'es') return font;
  const k = current + font;
  let f = fontCache.get(k);
  if (f === undefined) {
    f = font;
    if (current === 'vi') f = f.replace(/'Orbitron'/g, "'Exo 2'").replace(/'Rajdhani'/g, "'Chakra Petch'");
    const extra = current === 'vi' ? VI_FALLBACK : CJK;
    // Before the trailing generic family (sans-serif, serif, monospace, cursive), or at the end.
    f = /,\s*(sans-serif|serif|monospace|cursive|system-ui)\s*$/.test(f)
      ? f.replace(/,\s*(sans-serif|serif|monospace|cursive|system-ui)\s*$/, `, ${extra}, $1`)
      : `${f}, ${extra}`;
    fontCache.set(k, f);
  }
  return f;
}

let fontsPatched = false;
/** Route every canvas `font =` through localFont (a no-op in English and Spanish). */
export function installCanvasFonts(): void {
  if (fontsPatched) return;
  fontsPatched = true;
  const protos = [typeof CanvasRenderingContext2D !== 'undefined' ? CanvasRenderingContext2D.prototype : null,
    typeof OffscreenCanvasRenderingContext2D !== 'undefined' ? OffscreenCanvasRenderingContext2D.prototype : null];
  for (const p of protos) {
    if (!p) continue;
    const d = Object.getOwnPropertyDescriptor(p, 'font');
    if (!d || !d.set || !d.get) continue;
    const { get, set } = d;
    Object.defineProperty(p, 'font', {
      configurable: true,
      enumerable: d.enumerable,
      get(this: CanvasRenderingContext2D) {
        return get.call(this);
      },
      set(this: CanvasRenderingContext2D, v: string) {
        set.call(this, current === 'en' || current === 'es' ? v : localFont(v));
      },
    });
  }
}

let viFontsLoaded = false;
/** Vietnamese web fonts (Google Fonts serves only the subsets a page uses). */
export function loadLangFonts(): void {
  if (current !== 'vi' || viFontsLoaded) return;
  viFontsLoaded = true;
  const l = document.createElement('link');
  l.rel = 'stylesheet';
  l.href = 'https://fonts.googleapis.com/css2?family=Exo+2:wght@500;700;800;900&family=Chakra+Petch:wght@400;600;700&display=swap';
  // Canvas-only faces load lazily: ask for the Vietnamese glyphs up front.
  l.onload = () => {
    for (const f of ["900 16px 'Exo 2'", "700 16px 'Exo 2'", "700 16px 'Chakra Petch'", "600 16px 'Chakra Petch'"]) void document.fonts?.load(f, 'ẾƯỜđ').catch(() => {});
  };
  document.head.appendChild(l);
}

/** True if `s` has Chinese / Japanese / Korean characters (wrapped per character, not per word). */
export function hasCjk(s: string): boolean {
  return /[\u2E80-\u9FFF\uF900-\uFAFF\uFF00-\uFFEF]/.test(s);
}

