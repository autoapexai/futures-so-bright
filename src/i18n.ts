export function t(key: Key, vars?: Record<string, string | number>): string {
  const s = STRINGS[current][key] ?? en[key];
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

